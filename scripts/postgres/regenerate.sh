#!/usr/bin/env bash
# Rebuilds 01-schema.sql and 02-reference-data.sql from the Prisma migrations
# and the production seed, so the SQL files cannot drift from the schema.
# Run it from the repository root after adding a Prisma migration:
#
#   SQLGEN_ADMIN_URL=postgresql://postgres:postgres@127.0.0.1:5432/postgres \
#     bash scripts/postgres/regenerate.sh
#
# SQLGEN_ADMIN_URL must be able to CREATE/DROP DATABASE. The scratch database
# (SQLGEN_DB, default miladwani_sqlgen) is dropped and recreated each run.
# Needs psql and pg_dump on PATH (any version >= the server's), and npm ci.
set -euo pipefail

: "${SQLGEN_ADMIN_URL:?set SQLGEN_ADMIN_URL to a PostgreSQL URL that can create databases}"
DB="${SQLGEN_DB:-miladwani_sqlgen}"
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
cd "$ROOT"

# The scratch database's URL: the admin URL with its database name replaced.
DB_URL="$(node -e 'const u=new URL(process.argv[1]); u.pathname="/"+process.argv[2]; u.searchParams.set("schema","public"); console.log(u.toString())' "$SQLGEN_ADMIN_URL" "$DB")"
PG_URL="${DB_URL%%\?*}" # psql/pg_dump do not understand ?schema=

psql "$SQLGEN_ADMIN_URL" -v ON_ERROR_STOP=1 -qc "DROP DATABASE IF EXISTS \"$DB\"" -c "CREATE DATABASE \"$DB\""

# Reference data only: SEED_TEST_ACCOUNTS is forced off so no test login can
# leak into a production file, and the admin password is the documented one.
env -u SEED_TEST_ACCOUNTS DATABASE_URL="$DB_URL" \
  ADMIN_EMAIL=admin@miladwani.com ADMIN_PASSWORD='ChangeThisInProduction123!' \
  sh -c 'npx prisma migrate deploy && npm run db:seed' >/dev/null

MIGRATIONS=(prisma/migrations/*/migration.sql)

# ── 01-schema.sql ────────────────────────────────────────────────
{
  cat <<'EOF'
-- ===========================================================================
-- Mi Ladwani — 01-schema.sql  (STRUCTURE ONLY, plus Prisma's migration record)
--
-- Run this FIRST, then 02-reference-data.sql, into the same EMPTY database.
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f scripts/postgres/01-schema.sql
-- (psql does not accept Prisma's ?schema=public suffix; drop it here.)
-- Any SQL console (pgAdmin, DBeaver, a provider's web console) works too:
-- the file is plain SQL with no psql meta-commands.
--
-- It is the Prisma migration history concatenated, inside one transaction:
-- if anything fails, nothing is left behind. It also creates Prisma's
-- _prisma_migrations table and records every migration as applied, with the
-- same checksum `prisma migrate deploy` would store, so a later
-- `npx prisma migrate deploy` sees nothing to do instead of trying to
-- re-create every table.
--
-- Needs the citext and btree_gist extensions (created below). Both are
-- "trusted" extensions, so the database owner can create them.
--
-- GENERATED by scripts/postgres/regenerate.sh — do not edit by hand.
-- ===========================================================================

BEGIN;

EOF
  for m in "${MIGRATIONS[@]}"; do
    echo "-- ───────────────────────────────────────────────────────────────────────────"
    echo "-- Migration $(basename "$(dirname "$m")")"
    echo "-- ───────────────────────────────────────────────────────────────────────────"
    cat "$m"
    echo
  done
  cat <<'EOF'
-- ───────────────────────────────────────────────────────────────────────────
-- Prisma's migration bookkeeping (same shape `prisma migrate deploy` creates)
-- ───────────────────────────────────────────────────────────────────────────
CREATE TABLE "_prisma_migrations" (
    "id"                  VARCHAR(36) NOT NULL,
    "checksum"            VARCHAR(64) NOT NULL,
    "finished_at"         TIMESTAMPTZ,
    "migration_name"      VARCHAR(255) NOT NULL,
    "logs"                TEXT,
    "rolled_back_at"      TIMESTAMPTZ,
    "started_at"          TIMESTAMPTZ NOT NULL DEFAULT now(),
    "applied_steps_count" INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT "_prisma_migrations_pkey" PRIMARY KEY ("id")
);

EOF
  for m in "${MIGRATIONS[@]}"; do
    name="$(basename "$(dirname "$m")")"
    sum="$(sha256sum "$m" | cut -d' ' -f1)"
    echo "INSERT INTO \"_prisma_migrations\" (\"id\", \"checksum\", \"finished_at\", \"migration_name\", \"applied_steps_count\")"
    echo "VALUES (gen_random_uuid()::text, '$sum', now(), '$name', 1);"
  done
  echo
  echo "COMMIT;"
} > "$HERE/01-schema.sql"

# ── 02-reference-data.sql ────────────────────────────────────────
DUMP="$(mktemp)"
trap 'rm -f "$DUMP"' EXIT
# --on-conflict-do-nothing makes a re-import harmless. pg_dump orders tables
# so that referenced rows come first.
pg_dump "$PG_URL" --data-only --column-inserts --rows-per-insert=100 \
  --on-conflict-do-nothing --exclude-table=_prisma_migrations \
  --no-owner --no-privileges -f "$DUMP" 2>/dev/null

{
  cat <<'EOF'
-- ===========================================================================
-- Mi Ladwani — 02-reference-data.sql  (DATA ONLY: no CREATE TABLE)
--
-- Run this SECOND, after 01-schema.sql, into the same database.
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f scripts/postgres/02-reference-data.sql
--
-- Contains ONLY the reference/config data `npm run db:seed` creates: roles,
-- the permission matrix, relationship types, approval rules, post types,
-- areas and districts, income ranges, settings, the family registration fee
-- type, the interest catalogue, and ONE admin login:
--
--       admin@miladwani.com / ChangeThisInProduction123!
--       ^ CHANGE THIS PASSWORD IMMEDIATELY AFTER YOUR FIRST LOGIN.
--
-- Contains NO test accounts, NO families, NO member data. Every INSERT is
-- ON CONFLICT DO NOTHING, so importing it twice changes nothing.
--
-- GENERATED by scripts/postgres/regenerate.sh — do not edit by hand.
-- ===========================================================================

BEGIN;

EOF
  # Keep only the INSERT statements (each spans its VALUES rows up to the
  # line ending in ';'), unqualified so they follow the session's
  # search_path. pg_dump's SET lines and psql-only \restrict lines are left
  # out, so any SQL client can run the file.
  awk '
    /^INSERT INTO / { table=$3; sub(/^public\./, "", table); print "-- " table; sub(/^INSERT INTO public\./, "INSERT INTO "); ins=1 }
    ins { print; if ($0 ~ /;$/) { ins=0; print "" } }
  ' "$DUMP"
  echo "COMMIT;"
} > "$HERE/02-reference-data.sql"

leaks="$(grep -c 'example\.test\|uat\.test' "$HERE/02-reference-data.sql" || true)"
if [ "$leaks" != "0" ]; then
  echo "02-reference-data.sql contains test accounts ($leaks lines) — refusing to keep it" >&2
  exit 1
fi

psql "$SQLGEN_ADMIN_URL" -qc "DROP DATABASE IF EXISTS \"$DB\""
echo "Regenerated $HERE/01-schema.sql and $HERE/02-reference-data.sql"
