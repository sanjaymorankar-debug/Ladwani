-- ─────────────────────────────────────────────────────────────────
-- Not generated by Prisma: double-booking prevention.
--
-- An application-level "is this slot free?" check loses the race when two
-- members submit overlapping bookings at the same moment: both read "free",
-- both insert. This exclusion constraint makes overlapping active bookings
-- for the same asset physically impossible, so the second one fails no
-- matter how the requests interleave. (The MySQL port had to replace it with
-- a row lock in the booking route; that lock is still there, so the common
-- case gets a clean "slot taken" answer before this constraint is reached.)
--
-- Only PENDING_PAYMENT and CONFIRMED block the slot; cancelled, completed,
-- rejected and expired bookings free it up again. Ranges are half-open
-- ([startAt, endAt)), so back-to-back bookings do not collide.
-- ─────────────────────────────────────────────────────────────────
ALTER TABLE "bookings"
  ADD CONSTRAINT "bookings_no_overlap"
  EXCLUDE USING gist (
    "assetId" WITH =,
    tsrange("startAt", "endAt", '[)') WITH &&
  )
  WHERE ("status" IN ('PENDING_PAYMENT', 'CONFIRMED'));

